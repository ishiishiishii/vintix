#!/usr/bin/env python3
"""Build dataset YAML + symlinks for successful narrow-DR PPO histories.

Uses ``dr_robots_ppo_history/outputs/dr_narrow_expert_rewards.csv`` and keeps
robots with ``reward_last >= REWARD_MIN`` (default 15). Symlinks each robot's
``ppo_history`` under ``data/dr_narrow_success/<robot_id>/`` so
``train_vintix --data_dir data`` can resolve relative paths.
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

EXP_DIR = Path(__file__).resolve().parent
VINTIX_ROOT = EXP_DIR.parent
GEN_DIR = VINTIX_ROOT / "dr_robots_ppo_history" / "dr_narrow_genloco" / "generated"
REWARD_CSV = VINTIX_ROOT / "dr_robots_ppo_history" / "outputs" / "dr_narrow_expert_rewards.csv"
LINK_ROOT = VINTIX_ROOT / "data" / "dr_narrow_success"
YAML_PATH = EXP_DIR / "configs" / "dr_narrow_success_dataset.yaml"
META_PATH = EXP_DIR / "configs" / "dr_narrow_success_meta.json"
GROUP = "quadruped_locomotion"  # shared decoder so Go1 unknown-task eval can attach
REWARD_MIN = 15.0


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--reward_min", type=float, default=REWARD_MIN)
    p.add_argument("--dry_run", action="store_true")
    args = p.parse_args()

    rows = list(csv.DictReader(REWARD_CSV.open()))
    ok = [r for r in rows if float(r["reward_last"]) >= args.reward_min]
    ok.sort(key=lambda r: r["robot_id"])
    if not ok:
        raise SystemExit(f"no robots with reward_last >= {args.reward_min}")

    LINK_ROOT.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Auto-generated by build_dataset.py — do not edit by hand.",
        f"# Successful narrow-DR robots (reward_last >= {args.reward_min}): {len(ok)} / {len(rows)}",
        f"# Group: {GROUP} (shared decoder for Go1 unknown-task eval)",
        "",
    ]
    meta = {
        "reward_min": args.reward_min,
        "n_total": len(rows),
        "n_success": len(ok),
        "group": GROUP,
        "robots": [],
    }

    missing = []
    for r in ok:
        rid = r["robot_id"]
        src = (GEN_DIR / rid / "ppo_history").resolve()
        if not src.is_dir() or not list(src.glob("trajectories_env_*.h5")):
            missing.append(rid)
            continue
        dst = LINK_ROOT / rid
        if not args.dry_run:
            if dst.is_symlink() or dst.exists():
                if dst.is_symlink() and dst.resolve() == src:
                    pass
                else:
                    if dst.is_symlink() or dst.is_file():
                        dst.unlink()
                    elif dst.is_dir() and not any(dst.iterdir()):
                        dst.rmdir()
                    else:
                        # replace stale link/dir
                        if dst.is_symlink():
                            dst.unlink()
                        else:
                            raise SystemExit(f"refusing to overwrite non-empty {dst}")
            if not dst.exists():
                dst.symlink_to(src, target_is_directory=True)

        rel = f"dr_narrow_success/{rid}"
        lines.append(f"{rid}:")
        lines.append(f'  type: "default"')
        lines.append(f'  path: "{rel}"')
        lines.append(f'  group: "{GROUP}"')
        lines.append(f"  reward_scale: 1.0")
        lines.append(f"  episode_sparsity: 1")
        lines.append("")
        meta["robots"].append(
            {
                "robot_id": rid,
                "reward_last": float(r["reward_last"]),
                "total_mass_kg": float(r["total_mass_kg"]),
                "leg_length_m": float(r["leg_length_m"]),
                "alpha": float(r["alpha"]),
                "path": rel,
            }
        )

    if missing:
        raise SystemExit(f"missing histories for {len(missing)} robots: {missing[:5]}")

    if args.dry_run:
        print(json.dumps({"n_success": len(ok), "yaml": str(YAML_PATH)}, indent=2))
        return

    YAML_PATH.parent.mkdir(parents=True, exist_ok=True)
    YAML_PATH.write_text("\n".join(lines) + "\n")
    META_PATH.write_text(json.dumps(meta, indent=2))
    print(f"wrote {YAML_PATH} ({len(ok)} tasks)")
    print(f"wrote {META_PATH}")
    print(f"symlinks under {LINK_ROOT}")


if __name__ == "__main__":
    main()
